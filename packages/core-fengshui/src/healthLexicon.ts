/**
 * 病名词表 —— README 规则 8「病名在 schema 层排除」的执行者。
 *
 * 风水断语可以说「此方脾胃方面宜留意」，不可以说「须留意恶性肿瘤」。
 * 前者是传统取象，后者是没有医学依据的诊断，既吓人也可能耽误就医。
 *
 * 用法：测试把所有面向使用者的文字过一遍本词表，命中即失败。
 *
 * 两类刻意不列入：
 *   1. 可判定的「事件」词（手术、住院、外伤、缝合）—— 对轨与占局的结算判据必须具体，
 *      「是否住院三天以上」才可判定；它们只出现在 resolution.criterion，不出现在断语标题。
 *   2. 古籍原文（`classic`、`classical` 字段）—— 引文须逐字，不可改写；它们不计入检测。
 */

export const DISEASE_TERMS: readonly string[] = [
  '癌', '肿瘤', '心脏病', '心血管', '高血压', '血压', '糖尿', '中风', '偏枯',
  '流产', '难产', '不孕', '慢性病', '病史', '抑郁', '焦虑', '神经衰弱', '哮喘',
  '肝炎', '肾虚', '性病', '重病', '久病', '急症', '急重症', '重症', '贫血',
  '炎症', '关节炎', '鼻炎', '肺病', '肺疾', '目疾', '眼疾', '腹疾', '耳聋',
  '耳鸣', '失眠', '心悸', '精神病', '精神疾患', '痴呆', '妇疾', '妇科', '吐血',
  '恶疮', '乳疾', '水肿', '中毒',
  // 死亡、自伤、绝后一类恐吓性断语
  '自缢', '绝嗣', '横死', '伤亡', '夭折', '丧命', '罹死亡',
] as const;

/** 返回文本中命中的病名词（去重）；无命中返回空数组。 */
export function findDiseaseTerms(text: string): string[] {
  const hits = new Set<string>();
  for (const t of DISEASE_TERMS) if (text.includes(t)) hits.add(t);
  return [...hits];
}
